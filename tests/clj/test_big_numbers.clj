;; ---- Ratio Tests ----
(check "ratio from int div" (str (/ 22 7)) "22/7")
(check "ratio from int div simple" (str (/ 25 4)) "25/4")
(check "ratio from int div exact" (/ 10 5) 2)
(check "ratio from int div by 1" (/ 25 1) 25)
(check "ratio add" (str (+ (/ 1 3) (/ 1 6))) "1/2")
(check "ratio mul" (str (* (/ 2 3) (/ 3 4))) "1/2")
(check "ratio div" (str (/ (/ 1 2) (/ 1 4))) "2")
(check "ratio add int" (str (+ (/ 1 3) 1)) "4/3")
(check "ratio mul int" (str (* (/ 1 3) 3)) "1")
(check "ratio number?" (number? (/ 1 2)) true)
(check "ratio from int / bigint" (str (/ 100 123456789012345678901234567890)) "10/12345678901234567890123456789")
(check "ratio neg" (str (/ -10 3)) "-10/3")
(check "ratio neg 2" (str (/ 10 -3)) "-10/3")
(check "ratio neg 3" (str (/ -10 -3)) "10/3")

;; ---- BigDecimal Tests ----
(check "decimal literal M" (str 123.456M) "123.456")
(check "decimal neg literal" (str -2.5M) "-2.5")
(check "decimal add" (str (+ 1.5M 2.5M)) "4.0")
(check "decimal mul" (str (* 1.5M 2.5M)) "3.75")
(check "decimal div" (str (/ 10.0M 3.0M)) "0.33333333333333333333")
(check "decimal sub" (str (- 10.0M 3.5M)) "6.5")
(check "decimal eq" (= 1.5M 1.5M) true)
(check "decimal number?" (number? 1.5M) true)
(check "decimal from int" (str (+ 1.5M 2)) "3.5")
(check "decimal mul int" (str (* 1.5M 2)) "3.0")
(check "decimal neg add" (str (+ -1.5M 2.5M)) "1.0")
(check "decimal neg mul" (str (* -1.5M 2.5M)) "-3.75")
(check "decimal neg div" (str (/ -10.0M 3.0M)) "-0.33333333333333333333")
(check "decimal neg sub" (str (- 0 2.5M)) "-2.5")

