(check "neg in add" (+ -5 3) -2)
(check "pos int literal" +5 5)
(check "neg div ratio" (str (/ -100 3)) "-100/3")
(check "neg div ratio 2" (str (/ 100 -3)) "-100/3")
(check "neg div ratio 3" (str (/ -100 -3)) "100/3")

