(load-file "tests/clj/clj_test_helper.clj")

;; ---- BigInt Literal Tests ----
(check "bigint N suffix" (str 123456789012345678901234567890N) "123456789012345678901234567890")
(check "bigint auto overflow" (str 123456789012345678901234567890) "123456789012345678901234567890")
